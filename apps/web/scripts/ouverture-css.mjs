/**
 * Builds src/styles/ouverture.vendor.css from the vendor form CSS (public/ouverture/app.css):
 * 1. scopes every rule under .ouverture-app (the site's CSS and the form's CSS do not leak into each other);
 * 2. maps the vendor's sage greens onto the site charter (forest hue for darks, warm neutrals for tints);
 * 3. replaces the Georgia display face with the site font token.
 * Run after a vendor update: bun apps/web/scripts/ouverture-css.mjs   (then check with --check)
 * Brand adjustments live in src/styles/ouverture.css, not here.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import assert from 'node:assert/strict'

const webDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const src = path.resolve(webDir, '../../public/ouverture/app.css')
const out = path.join(webDir, 'src/styles/ouverture.vendor.css')

function hexToHsl(hex) {
  let h = hex.slice(1)
  if (h.length === 3) h = [...h].map((c) => c + c).join('')
  const alpha = h.length === 8 ? h.slice(6) : ''
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255)
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2
  const d = max - min
  const s = d === 0 ? 0 : d / (1 - Math.abs(2 * l - 1))
  let hue = 0
  if (d) hue = max === r ? ((g - b) / d) % 6 : max === g ? (b - r) / d + 2 : (r - g) / d + 4
  return { h: (hue * 60 + 360) % 360, s, l, alpha }
}
function hslToHex({ h, s, l, alpha }) {
  const k = (n) => (n + h / 30) % 12
  const a = s * Math.min(l, 1 - l)
  const f = (n) => Math.round(255 * (l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)))))
  return '#' + [f(0), f(8), f(4)].map((v) => v.toString(16).padStart(2, '0')).join('') + alpha
}

/** Charter: forest #0E2826 (hue 174), gold #B68A3E, warm neutrals #f0eee9 / #dcdad2 / #faf8f4. */
export function charterColor(hex) {
  const c = hexToHsl(hex)
  if (c.h < 60 || c.h > 200 || c.s < 0.04) return hex.toLowerCase() // golds, reds, greys, white: keep
  if (c.l > 0.8) return hslToHex({ ...c, h: 43, s: Math.min(c.s, 0.22) }) // sage tint -> warm neutral
  return hslToHex({ ...c, h: 174, s: c.s * (c.l < 0.3 ? 1 : 0.7) }) // green ink/line -> forest family
}

export function scope(css) {
  const body = css
    .replace(/@charset[^;]+;/g, '')
    // Vendor file ends with declarations that have no selector (browsers drop them; Tailwind's parser fails).
    .replace(/\}[^{}]*\}\s*$/, '}')
    .replace(/:root/g, '&')
    .replace(/(^|[\s,{}])body(?=[\s,{.[:])/g, '$1&')
    .replace(/font-family:\s*Georgia,\s*serif/g, 'font-family:var(--font-display)')
    .replace(/#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b/g, charterColor)
  return `/* GENERATED by apps/web/scripts/ouverture-css.mjs from public/ouverture/app.css. Do not edit. */\n.ouverture-app {\n${body}\n}\n`
}

// Self-check: the mapping keeps the brand colours and moves sage tints to warm neutrals.
assert.equal(charterColor('#B68A3E'), '#b68a3e')
assert.equal(charterColor('#fff'), '#fff')
assert.equal(charterColor('#B3261E'), '#b3261e')
const hue = (hex) => hexToHsl(charterColor(hex)).h // 8-bit rounding moves the hue a few degrees
assert.ok(Math.abs(hue('#f3f6ee') - 43) < 8)
assert.ok(Math.abs(hue('#2f5a3f') - 174) < 4)
assert.doesNotMatch(scope('.a{b:1}c:1}'), /c:1/)
assert.match(scope(':root{--a:1}body{x:1}body.show-refs .r{y:1}'), /&\{--a:1\}&\{x:1\}&\.show-refs \.r/)

const generated = scope(fs.readFileSync(src, 'utf8'))
if (process.argv.includes('--check')) {
  assert.equal(fs.readFileSync(out, 'utf8'), generated, 'ouverture.vendor.css is stale: run bun apps/web/scripts/ouverture-css.mjs')
  console.log('ouverture css: up to date')
} else {
  fs.writeFileSync(out, generated)
  console.log(`ouverture css: wrote ${path.relative(process.cwd(), out)}`)
}
